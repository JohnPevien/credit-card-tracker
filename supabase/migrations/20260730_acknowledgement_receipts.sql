-- Incremental acknowledgement-receipt schema.
-- Existing public.persons(id) and public.transactions(id) relations are required.
-- All browser-facing access is server mediated; no receipt object is public.

BEGIN;

CREATE SEQUENCE IF NOT EXISTS public.ack_receipt_number_seq
    AS bigint
    START WITH 1
    INCREMENT BY 1
    NO CYCLE;

CREATE TABLE IF NOT EXISTS public.payer_portal_access (
    person_id uuid PRIMARY KEY
        REFERENCES public.persons(id) ON DELETE CASCADE,
    public_id uuid NOT NULL DEFAULT gen_random_uuid(),
    pin_hash text NOT NULL,
    credential_version integer NOT NULL DEFAULT 1
        CHECK (credential_version > 0),
    revoked_at timestamptz,
    last_accessed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT payer_portal_access_public_id_key UNIQUE (public_id),
    CONSTRAINT payer_portal_access_pin_hash_check
        CHECK (length(pin_hash) >= 16)
);

CREATE TABLE IF NOT EXISTS public.payer_portal_pin_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portal_person_id uuid NOT NULL
        REFERENCES public.payer_portal_access(person_id) ON DELETE CASCADE,
    network_hash text NOT NULL,
    succeeded boolean NOT NULL DEFAULT false,
    attempted_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT payer_portal_pin_attempts_network_hash_check
        CHECK (length(network_hash) BETWEEN 16 AND 256)
);

CREATE TABLE IF NOT EXISTS public.acknowledgement_receipts (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    receipt_number text NOT NULL,
    payer_person_id uuid NOT NULL
        REFERENCES public.persons(id) ON DELETE RESTRICT,
    payer_name_snapshot text NOT NULL,
    receiver_name text NOT NULL,
    amount numeric(14, 2) NOT NULL,
    currency char(3) NOT NULL DEFAULT 'PHP',
    payment_date date NOT NULL,
    notes text,
    revision_number integer NOT NULL DEFAULT 1,
    published_at timestamptz,
    payer_confirmed_at timestamptz,
    receiver_confirmed_at timestamptz,
    completed_at timestamptz,
    is_completed boolean GENERATED ALWAYS AS (completed_at IS NOT NULL) STORED,
    voided_at timestamptz,
    void_reason text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT acknowledgement_receipts_receipt_number_key
        UNIQUE (receipt_number),
    CONSTRAINT acknowledgement_receipts_receipt_number_check
        CHECK (receipt_number ~ '^AR-[0-9]{4}-[0-9]{6}$'),
    CONSTRAINT acknowledgement_receipts_payer_name_check
        CHECK (
            length(btrim(payer_name_snapshot)) BETWEEN 1 AND 200
            AND payer_name_snapshot = btrim(payer_name_snapshot)
        ),
    CONSTRAINT acknowledgement_receipts_receiver_name_check
        CHECK (
            length(btrim(receiver_name)) BETWEEN 1 AND 200
            AND receiver_name = btrim(receiver_name)
        ),
    CONSTRAINT acknowledgement_receipts_amount_check
        CHECK (amount > 0),
    CONSTRAINT acknowledgement_receipts_currency_check
        CHECK (currency::text ~ '^[A-Z]{3}$'),
    CONSTRAINT acknowledgement_receipts_notes_check
        CHECK (notes IS NULL OR length(notes) <= 5000),
    CONSTRAINT acknowledgement_receipts_revision_check
        CHECK (revision_number > 0),
    CONSTRAINT acknowledgement_receipts_confirmation_check
        CHECK (
            completed_at IS NULL
            OR (
                published_at IS NOT NULL
                AND payer_confirmed_at IS NOT NULL
                AND receiver_confirmed_at IS NOT NULL
            )
        ),
    CONSTRAINT acknowledgement_receipts_published_confirmation_check
        CHECK (
            published_at IS NOT NULL
            OR (
                payer_confirmed_at IS NULL
                AND receiver_confirmed_at IS NULL
                AND completed_at IS NULL
            )
        ),
    CONSTRAINT acknowledgement_receipts_void_check
        CHECK (
            (voided_at IS NULL AND void_reason IS NULL)
            OR (
                voided_at IS NOT NULL
                AND void_reason IS NOT NULL
                AND length(btrim(void_reason)) BETWEEN 1 AND 1000
            )
        )
);

CREATE TABLE IF NOT EXISTS public.acknowledgement_receipt_transactions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    receipt_id uuid NOT NULL
        REFERENCES public.acknowledgement_receipts(id) ON DELETE CASCADE,
    transaction_id uuid
        REFERENCES public.transactions(id) ON DELETE SET NULL,
    transaction_date_snapshot date NOT NULL,
    description_snapshot text NOT NULL,
    amount_snapshot numeric(14, 2) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT acknowledgement_receipt_transactions_description_check
        CHECK (length(btrim(description_snapshot)) > 0)
);

CREATE TABLE IF NOT EXISTS public.acknowledgement_receipt_files (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    receipt_id uuid NOT NULL
        REFERENCES public.acknowledgement_receipts(id) ON DELETE CASCADE,
    storage_path text NOT NULL,
    original_filename text NOT NULL,
    content_type text NOT NULL,
    size_bytes bigint NOT NULL,
    uploader_role text NOT NULL,
    removed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT acknowledgement_receipt_files_storage_path_key
        UNIQUE (storage_path),
    CONSTRAINT acknowledgement_receipt_files_storage_path_check
        CHECK (length(btrim(storage_path)) BETWEEN 1 AND 1024),
    CONSTRAINT acknowledgement_receipt_files_filename_check
        CHECK (length(btrim(original_filename)) BETWEEN 1 AND 255),
    CONSTRAINT acknowledgement_receipt_files_content_type_check
        CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
    CONSTRAINT acknowledgement_receipt_files_size_check
        CHECK (size_bytes > 0 AND size_bytes <= 10 * 1024 * 1024),
    CONSTRAINT acknowledgement_receipt_files_uploader_role_check
        CHECK (uploader_role IN ('payer', 'receiver'))
);

CREATE TABLE IF NOT EXISTS public.acknowledgement_receipt_revisions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    receipt_id uuid NOT NULL
        REFERENCES public.acknowledgement_receipts(id) ON DELETE CASCADE,
    revision_number integer NOT NULL,
    snapshot jsonb NOT NULL,
    change_reason text NOT NULL,
    changed_by_role text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT acknowledgement_receipt_revisions_receipt_revision_key
        UNIQUE (receipt_id, revision_number),
    CONSTRAINT acknowledgement_receipt_revisions_revision_check
        CHECK (revision_number > 0),
    CONSTRAINT acknowledgement_receipt_revisions_snapshot_check
        CHECK (jsonb_typeof(snapshot) = 'object'),
    CONSTRAINT acknowledgement_receipt_revisions_reason_check
        CHECK (length(btrim(change_reason)) BETWEEN 1 AND 1000),
    CONSTRAINT acknowledgement_receipt_revisions_role_check
        CHECK (changed_by_role IN ('payer', 'receiver', 'system'))
);

CREATE TABLE IF NOT EXISTS public.acknowledgement_receipt_events (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    receipt_id uuid
        REFERENCES public.acknowledgement_receipts(id) ON DELETE CASCADE,
    portal_person_id uuid
        REFERENCES public.payer_portal_access(person_id) ON DELETE CASCADE,
    event_type text NOT NULL,
    actor_role text NOT NULL,
    revision_number integer,
    details jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT acknowledgement_receipt_events_type_check
        CHECK (length(btrim(event_type)) BETWEEN 1 AND 100),
    CONSTRAINT acknowledgement_receipt_events_actor_role_check
        CHECK (actor_role IN ('payer', 'receiver', 'system')),
    CONSTRAINT acknowledgement_receipt_events_subject_check
        CHECK (
            (
                receipt_id IS NOT NULL
                AND portal_person_id IS NULL
                AND revision_number IS NOT NULL
                AND revision_number > 0
            )
            OR (
                receipt_id IS NULL
                AND portal_person_id IS NOT NULL
                AND revision_number IS NULL
            )
        ),
    CONSTRAINT acknowledgement_receipt_events_details_check
        CHECK (jsonb_typeof(details) = 'object')
);

CREATE INDEX IF NOT EXISTS payer_portal_pin_attempts_portal_idx
