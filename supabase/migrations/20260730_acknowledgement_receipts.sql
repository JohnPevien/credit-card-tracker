CREATE OR REPLACE FUNCTION public.ack_snapshot_receipt(
    p_receipt_id uuid,
    p_change_reason text,
    p_changed_by_role text
)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_receipt public.acknowledgement_receipts%ROWTYPE;
    v_snapshot jsonb;
    v_status text;
BEGIN
    IF p_changed_by_role NOT IN ('payer', 'receiver', 'system') THEN
        RAISE EXCEPTION 'invalid receipt actor role'
            USING ERRCODE = '22023';
    END IF;

    SELECT *
    INTO v_receipt
    FROM public.acknowledgement_receipts
    WHERE id = p_receipt_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE no_data_found;
    END IF;

    v_status := CASE
        WHEN v_receipt.voided_at IS NOT NULL THEN 'voided'
        WHEN v_receipt.published_at IS NULL THEN 'draft'
        WHEN (
            v_receipt.completed_at IS NOT NULL
            AND v_receipt.payer_confirmed_at IS NOT NULL
            AND v_receipt.receiver_confirmed_at IS NOT NULL
        ) THEN 'completed'
        WHEN (
            v_receipt.payer_confirmed_at IS NULL
            AND v_receipt.receiver_confirmed_at IS NOT NULL
        ) THEN 'awaiting_payer'
        WHEN (
            v_receipt.payer_confirmed_at IS NOT NULL
            AND v_receipt.receiver_confirmed_at IS NULL
        ) THEN 'awaiting_receiver'
        ELSE 'awaiting_both'
    END;

    v_snapshot := jsonb_build_object(
        'receipt',
        jsonb_build_object(
            'id', v_receipt.id,
            'receiptNumber', v_receipt.receipt_number,
            'payerPersonId', v_receipt.payer_person_id,
            'payerName', v_receipt.payer_name_snapshot,
            'receiverName', v_receipt.receiver_name,
            'amount', v_receipt.amount,
            'currency', btrim(v_receipt.currency::text),
            'paymentDate', v_receipt.payment_date,
            'notes', v_receipt.notes,
            'revisionNumber', v_receipt.revision_number,
            'publishedAt', v_receipt.published_at,
            'payerConfirmedAt', v_receipt.payer_confirmed_at,
            'receiverConfirmedAt', v_receipt.receiver_confirmed_at,
            'completedAt', v_receipt.completed_at,
            'isCompleted', v_receipt.is_completed,
            'voidedAt', v_receipt.voided_at,
            'voidReason', v_receipt.void_reason,
            'status', v_status,
            'createdAt', v_receipt.created_at,
            'updatedAt', v_receipt.updated_at
        ),
        'transactions',
        COALESCE(
            (
                SELECT jsonb_agg(
                    jsonb_build_object(
                        'id', receipt_transaction.id,
                        'transactionId', receipt_transaction.transaction_id,
                        'transactionDate',
                            receipt_transaction.transaction_date_snapshot,
                        'description',
                            receipt_transaction.description_snapshot,
                        'amount', receipt_transaction.amount_snapshot,
                        'createdAt', receipt_transaction.created_at
                    )
                    ORDER BY
                        receipt_transaction.created_at,
                        receipt_transaction.id
                )
                FROM public.acknowledgement_receipt_transactions receipt_transaction
                WHERE receipt_transaction.receipt_id = p_receipt_id
            ),
            '[]'::jsonb
        ),
        'proofs',
        COALESCE(
            (
                SELECT jsonb_agg(
                    jsonb_build_object(
                        'id', receipt_file.id,
                        'originalFilename', receipt_file.original_filename,
                        'contentType', receipt_file.content_type,
                        'sizeBytes', receipt_file.size_bytes,
                        'uploaderRole', receipt_file.uploader_role,
                        'removedAt', receipt_file.removed_at,
                        'createdAt', receipt_file.created_at
                    )
                    ORDER BY receipt_file.created_at, receipt_file.id
                )
                FROM public.acknowledgement_receipt_files receipt_file
                WHERE receipt_file.receipt_id = p_receipt_id
            ),
            '[]'::jsonb
        )
    );

    INSERT INTO public.acknowledgement_receipt_revisions (
        receipt_id,
        revision_number,
        snapshot,
        change_reason,
        changed_by_role
    )
    VALUES (
        p_receipt_id,
        v_receipt.revision_number,
        v_snapshot,
        p_change_reason,
        p_changed_by_role
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.ack_create_receipt(
    p_payer_person_id uuid,
    p_receiver_name text,
    p_amount numeric,
    p_currency text,
    p_payment_date date,
    p_notes text,
    p_transaction_ids uuid[]
)
RETURNS public.acknowledgement_receipts
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_receipt public.acknowledgement_receipts%ROWTYPE;
    v_payer_name text;
    v_sequence_value bigint;
    v_inserted_count integer;
    v_transaction_ids uuid[] := COALESCE(p_transaction_ids, ARRAY[]::uuid[]);
BEGIN
    IF (
        p_amount <= 0
        OR p_amount > 999999999999.99
        OR p_amount <> round(p_amount, 2)
    ) THEN
        RAISE EXCEPTION 'receipt amount must fit positive numeric(14,2)'
            USING ERRCODE = '22023';
    END IF;

    IF p_currency !~ '^[A-Z]{3}$' THEN
        RAISE EXCEPTION 'currency must be three uppercase letters'
            USING ERRCODE = '22023';
    END IF;

    IF cardinality(v_transaction_ids) <> (
        SELECT count(DISTINCT input_id)
        FROM unnest(v_transaction_ids) AS input_transaction(input_id)
    ) THEN
        RAISE EXCEPTION 'transaction ids must be unique'
            USING ERRCODE = '22023';
    END IF;

    SELECT btrim(name)
    INTO v_payer_name
    FROM public.persons
    WHERE id = p_payer_person_id;

    IF NOT FOUND THEN
        RAISE no_data_found;
    END IF;

    v_sequence_value := nextval('public.ack_receipt_number_seq');
    IF v_sequence_value > 999999 THEN
        RAISE EXCEPTION 'acknowledgement receipt sequence exhausted'
            USING ERRCODE = '54000';
    END IF;

    INSERT INTO public.acknowledgement_receipts (
        receipt_number,
        payer_person_id,
        payer_name_snapshot,
        receiver_name,
        amount,
        currency,
        payment_date,
        notes
    )
    VALUES (
        format(
            'AR-%s-%s',
            to_char(clock_timestamp() AT TIME ZONE 'Asia/Manila', 'YYYY'),
            lpad(v_sequence_value::text, 6, '0')
        ),
        p_payer_person_id,
        v_payer_name,
        btrim(p_receiver_name),
        p_amount,
        p_currency,
        p_payment_date,
        p_notes
    )
    RETURNING * INTO v_receipt;

    INSERT INTO public.acknowledgement_receipt_transactions (
        receipt_id,
        transaction_id,
        transaction_date_snapshot,
        description_snapshot,
        amount_snapshot
    )
    SELECT
        v_receipt.id,
        transaction_row.id,
        transaction_row.date,
        transaction_row.description,
        transaction_row.amount
    FROM public.transactions transaction_row
    WHERE transaction_row.id = ANY(v_transaction_ids)
      AND transaction_row.person_id = p_payer_person_id;

    GET DIAGNOSTICS v_inserted_count = ROW_COUNT;
    IF v_inserted_count <> cardinality(v_transaction_ids) THEN
        RAISE EXCEPTION 'all transactions must exist and belong to the payer'
            USING ERRCODE = '22023';
    END IF;

    INSERT INTO public.acknowledgement_receipt_events (
        receipt_id,
        event_type,
        actor_role,
        revision_number
    )
    VALUES (v_receipt.id, 'created', 'receiver', v_receipt.revision_number);

    RETURN v_receipt;
END;
$$;

CREATE OR REPLACE FUNCTION public.ack_update_receipt(
    p_receipt_id uuid,
    p_expected_revision integer,
    p_payer_person_id uuid,
    p_receiver_name text,
    p_amount numeric,
    p_currency text,
    p_payment_date date,
    p_notes text,
    p_transaction_ids uuid[]
)
RETURNS public.acknowledgement_receipts
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_receipt public.acknowledgement_receipts%ROWTYPE;
    v_payer_name text;
    v_inserted_count integer;
    v_had_confirmation boolean;
    v_is_unchanged boolean;
    v_transaction_ids uuid[] := COALESCE(p_transaction_ids, ARRAY[]::uuid[]);
BEGIN
    SELECT *
    INTO v_receipt
    FROM public.acknowledgement_receipts
    WHERE id = p_receipt_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE no_data_found;
    END IF;

    IF v_receipt.revision_number <> p_expected_revision THEN
        RAISE EXCEPTION 'acknowledgement receipt revision conflict'
            USING
                ERRCODE = '40001',
                DETAIL = format(
                    'expected revision %s, current revision %s',
                    p_expected_revision,
                    v_receipt.revision_number
                );
    END IF;

    IF v_receipt.voided_at IS NOT NULL THEN
        RAISE EXCEPTION 'voided receipts cannot be edited'
            USING ERRCODE = '55000';
    END IF;

    IF (
        p_amount <= 0
        OR p_amount > 999999999999.99
        OR p_amount <> round(p_amount, 2)
    ) THEN
        RAISE EXCEPTION 'receipt amount must fit positive numeric(14,2)'
            USING ERRCODE = '22023';
    END IF;

    IF p_currency !~ '^[A-Z]{3}$' THEN
        RAISE EXCEPTION 'currency must be three uppercase letters'
            USING ERRCODE = '22023';
    END IF;

    IF cardinality(v_transaction_ids) <> (
        SELECT count(DISTINCT input_id)
        FROM unnest(v_transaction_ids) AS input_transaction(input_id)
    ) THEN
        RAISE EXCEPTION 'transaction ids must be unique'
            USING ERRCODE = '22023';
    END IF;

    SELECT btrim(name)
    INTO v_payer_name
    FROM public.persons
    WHERE id = p_payer_person_id;

    IF NOT FOUND THEN
        RAISE no_data_found;
    END IF;

    v_is_unchanged := (
        v_receipt.payer_person_id IS NOT DISTINCT FROM p_payer_person_id
        AND v_receipt.payer_name_snapshot IS NOT DISTINCT FROM v_payer_name
        AND v_receipt.receiver_name IS NOT DISTINCT FROM btrim(p_receiver_name)
        AND v_receipt.amount IS NOT DISTINCT FROM p_amount
        AND btrim(v_receipt.currency::text) IS NOT DISTINCT FROM p_currency
        AND v_receipt.payment_date IS NOT DISTINCT FROM p_payment_date
        AND v_receipt.notes IS NOT DISTINCT FROM p_notes
        AND NOT EXISTS (
            SELECT receipt_transaction.transaction_id
            FROM public.acknowledgement_receipt_transactions receipt_transaction
            WHERE receipt_transaction.receipt_id = p_receipt_id
            EXCEPT
            SELECT input_transaction.input_id
            FROM unnest(v_transaction_ids) AS input_transaction(input_id)
        )
        AND NOT EXISTS (
            SELECT input_transaction.input_id
            FROM unnest(v_transaction_ids) AS input_transaction(input_id)
            EXCEPT
            SELECT receipt_transaction.transaction_id
            FROM public.acknowledgement_receipt_transactions receipt_transaction
            WHERE receipt_transaction.receipt_id = p_receipt_id
        )
    );

    IF v_is_unchanged THEN
        RETURN v_receipt;
    END IF;

    v_had_confirmation := (
        v_receipt.payer_confirmed_at IS NOT NULL
        OR v_receipt.receiver_confirmed_at IS NOT NULL
        OR v_receipt.completed_at IS NOT NULL
    );

    PERFORM public.ack_snapshot_receipt(
        p_receipt_id,
        'receipt content or transaction references updated',
        'receiver'
    );

    DELETE FROM public.acknowledgement_receipt_transactions
    WHERE receipt_id = p_receipt_id;

    INSERT INTO public.acknowledgement_receipt_transactions (
        receipt_id,
        transaction_id,
        transaction_date_snapshot,
        description_snapshot,
        amount_snapshot
    )
    SELECT
        p_receipt_id,
        transaction_row.id,
        transaction_row.date,
        transaction_row.description,
        transaction_row.amount
    FROM public.transactions transaction_row
    WHERE transaction_row.id = ANY(v_transaction_ids)
      AND transaction_row.person_id = p_payer_person_id;

    GET DIAGNOSTICS v_inserted_count = ROW_COUNT;
    IF v_inserted_count <> cardinality(v_transaction_ids) THEN
        RAISE EXCEPTION 'all transactions must exist and belong to the payer'
            USING ERRCODE = '22023';
    END IF;

    UPDATE public.acknowledgement_receipts
    SET
        payer_person_id = p_payer_person_id,
        payer_name_snapshot = v_payer_name,
        receiver_name = btrim(p_receiver_name),
        amount = p_amount,
        currency = p_currency,
        payment_date = p_payment_date,
        notes = p_notes,
        revision_number = revision_number + 1,
        payer_confirmed_at = NULL,
        receiver_confirmed_at = NULL,
        completed_at = NULL
    WHERE id = p_receipt_id
    RETURNING * INTO v_receipt;

    INSERT INTO public.acknowledgement_receipt_events (
        receipt_id,
        event_type,
        actor_role,
        revision_number
    )
    VALUES (
        p_receipt_id,
        'receipt_updated',
        'receiver',
        v_receipt.revision_number
    );

    IF v_had_confirmation THEN
        INSERT INTO public.acknowledgement_receipt_events (
            receipt_id,
            event_type,
            actor_role,
            revision_number,
            details
        )
        VALUES (
            p_receipt_id,
            'confirmation_reset',
            'receiver',
            v_receipt.revision_number,
            '{"reason":"receipt_updated"}'::jsonb
        );
    END IF;

    RETURN v_receipt;
END;
$$;

