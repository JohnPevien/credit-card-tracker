CREATE OR REPLACE FUNCTION public.ack_touch_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $$
BEGIN
    NEW.updated_at := clock_timestamp();
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.ack_reject_append_only()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $$
BEGIN
    RAISE EXCEPTION '% is append-only', TG_TABLE_NAME
        USING ERRCODE = '55000';
END;
$$;

CREATE OR REPLACE FUNCTION public.ack_enforce_active_file_limit()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_active_count integer;
BEGIN
    IF (
        TG_OP = 'UPDATE'
        AND NEW.receipt_id IS DISTINCT FROM OLD.receipt_id
    ) THEN
        RAISE EXCEPTION 'proof receipt_id is immutable'
            USING ERRCODE = '55000';
    END IF;

    IF NEW.removed_at IS NOT NULL THEN
        RETURN NEW;
    END IF;

    IF TG_OP = 'UPDATE' THEN
        IF OLD.removed_at IS NULL THEN
            RETURN NEW;
        END IF;
    END IF;

    PERFORM 1
    FROM public.acknowledgement_receipts
    WHERE id = NEW.receipt_id
    FOR UPDATE;

    SELECT count(*)
    INTO v_active_count
    FROM public.acknowledgement_receipt_files
    WHERE receipt_id = NEW.receipt_id
      AND removed_at IS NULL;

    IF v_active_count >= 5 THEN
        RAISE EXCEPTION 'a receipt may have at most five active files'
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

