    SELECT *
    INTO v_transaction
    FROM public.transactions
    WHERE id = p_transaction_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE no_data_found;
    END IF;

    UPDATE public.transactions
    SET paid = p_paid
    WHERE id = p_transaction_id;

    IF v_transaction.person_id IS DISTINCT FROM v_receipt.payer_person_id THEN
        RAISE EXCEPTION 'transaction and receipt must have the same payer'
            USING ERRCODE = '22023';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.acknowledgement_receipt_transactions
        WHERE receipt_id = p_receipt_id
          AND transaction_id = p_transaction_id
    ) THEN
        RETURN jsonb_build_object(
            'transaction_id', p_transaction_id,
            'paid', p_paid,
            'receipt_id', p_receipt_id,
            'receipt_revision', v_receipt.revision_number
        );
    END IF;

    v_had_confirmation := (
        v_receipt.payer_confirmed_at IS NOT NULL
        OR v_receipt.receiver_confirmed_at IS NOT NULL
        OR v_receipt.completed_at IS NOT NULL
    );

    PERFORM public.ack_snapshot_receipt(
        p_receipt_id,
        'transaction reference added while marking paid',
        'receiver'
    );

    INSERT INTO public.acknowledgement_receipt_transactions (
        receipt_id,
        transaction_id,
        transaction_date_snapshot,
        description_snapshot,
        amount_snapshot
    )
    VALUES (
        p_receipt_id,
        p_transaction_id,
        v_transaction.date,
        v_transaction.description,
        v_transaction.amount
    );

    UPDATE public.acknowledgement_receipts
    SET
        revision_number = revision_number + 1,
        payer_confirmed_at = NULL,
        receiver_confirmed_at = NULL,
        completed_at = NULL
    WHERE id = p_receipt_id
    RETURNING * INTO v_receipt;

    INSERT INTO public.acknowledgement_receipt_events (
        receipt_id,
        event_type,
        actor_role,
        revision_number,
        details
    )
    VALUES (
        p_receipt_id,
        'transaction_linked',
        'receiver',
        v_receipt.revision_number,
        jsonb_build_object('transaction_id', p_transaction_id)
    );

    IF v_had_confirmation THEN
        INSERT INTO public.acknowledgement_receipt_events (
            receipt_id,
            event_type,
            actor_role,
            revision_number,
            details
        )
        VALUES (
            p_receipt_id,
            'confirmation_reset',
            'receiver',
            v_receipt.revision_number,
            '{"reason":"transaction_linked"}'::jsonb
        );
    END IF;

    RETURN jsonb_build_object(
        'transaction_id', p_transaction_id,
        'paid', p_paid,
        'receipt_id', p_receipt_id,
        'receipt_revision', v_receipt.revision_number
    );
END;
$$;

CREATE OR REPLACE VIEW public.acknowledgement_receipt_overview
WITH (security_invoker = true)
AS
SELECT
    receipt.*,
    CASE
        WHEN receipt.voided_at IS NOT NULL THEN 'voided'
        WHEN receipt.published_at IS NULL THEN 'draft'
        WHEN (
            receipt.completed_at IS NOT NULL
            AND receipt.payer_confirmed_at IS NOT NULL
            AND receipt.receiver_confirmed_at IS NOT NULL
        ) THEN 'completed'
        WHEN (
            receipt.payer_confirmed_at IS NULL
            AND receipt.receiver_confirmed_at IS NOT NULL
        ) THEN 'awaiting_payer'
        WHEN (
            receipt.payer_confirmed_at IS NOT NULL
            AND receipt.receiver_confirmed_at IS NULL
        ) THEN 'awaiting_receiver'
        ELSE 'awaiting_both'
    END AS status,
    (
        SELECT count(*)
        FROM public.acknowledgement_receipt_transactions receipt_transaction
        WHERE receipt_transaction.receipt_id = receipt.id
    ) AS transaction_count,
    (
        SELECT count(*)
        FROM public.acknowledgement_receipt_files receipt_file
        WHERE receipt_file.receipt_id = receipt.id
          AND receipt_file.removed_at IS NULL
    ) AS proof_count
FROM public.acknowledgement_receipts receipt;

