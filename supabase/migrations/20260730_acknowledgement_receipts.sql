CREATE OR REPLACE FUNCTION public.ack_confirm_receipt(
    p_receipt_id uuid,
    p_expected_revision integer,
    p_role text
)
RETURNS public.acknowledgement_receipts
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_receipt public.acknowledgement_receipts%ROWTYPE;
    v_confirmed_at timestamptz := clock_timestamp();
    v_became_completed boolean := false;
BEGIN
    IF p_role NOT IN ('payer', 'receiver') THEN
        RAISE EXCEPTION 'confirmation role must be payer or receiver'
            USING ERRCODE = '22023';
    END IF;

    SELECT *
    INTO v_receipt
    FROM public.acknowledgement_receipts
    WHERE id = p_receipt_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE no_data_found;
    END IF;

    IF v_receipt.revision_number <> p_expected_revision THEN
        RAISE EXCEPTION 'acknowledgement receipt revision conflict'
            USING ERRCODE = '40001';
    END IF;

    IF v_receipt.published_at IS NULL THEN
        RAISE EXCEPTION 'draft receipts cannot be confirmed'
            USING ERRCODE = '55000';
    END IF;

    IF v_receipt.voided_at IS NOT NULL THEN
        RAISE EXCEPTION 'voided receipts cannot be confirmed'
            USING ERRCODE = '55000';
    END IF;

    IF (
        p_role = 'payer'
        AND v_receipt.payer_confirmed_at IS NOT NULL
    ) OR (
        p_role = 'receiver'
        AND v_receipt.receiver_confirmed_at IS NOT NULL
    ) THEN
        RETURN v_receipt;
    END IF;

    UPDATE public.acknowledgement_receipts
    SET
        payer_confirmed_at = CASE
            WHEN p_role = 'payer' THEN v_confirmed_at
            ELSE payer_confirmed_at
        END,
        receiver_confirmed_at = CASE
            WHEN p_role = 'receiver' THEN v_confirmed_at
            ELSE receiver_confirmed_at
        END
    WHERE id = p_receipt_id
    RETURNING * INTO v_receipt;

    IF (
        v_receipt.payer_confirmed_at IS NOT NULL
        AND v_receipt.receiver_confirmed_at IS NOT NULL
        AND v_receipt.completed_at IS NULL
    ) THEN
        UPDATE public.acknowledgement_receipts
        SET completed_at = v_confirmed_at
        WHERE id = p_receipt_id
        RETURNING * INTO v_receipt;
        v_became_completed := true;
    END IF;

    INSERT INTO public.acknowledgement_receipt_events (
        receipt_id,
        event_type,
        actor_role,
        revision_number
    )
    VALUES (
        p_receipt_id,
        p_role || '_confirmed',
        p_role,
        v_receipt.revision_number
    );

    IF v_became_completed THEN
        INSERT INTO public.acknowledgement_receipt_events (
            receipt_id,
            event_type,
            actor_role,
            revision_number
        )
        VALUES (
            p_receipt_id,
            'completed',
            p_role,
            v_receipt.revision_number
        );
    END IF;

    RETURN v_receipt;
END;
$$;

CREATE OR REPLACE FUNCTION public.ack_void_receipt(
    p_receipt_id uuid,
    p_expected_revision integer,
    p_reason text
)
RETURNS public.acknowledgement_receipts
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_receipt public.acknowledgement_receipts%ROWTYPE;
    v_reason text := btrim(p_reason);
BEGIN
    IF v_reason IS NULL OR length(v_reason) NOT BETWEEN 1 AND 1000 THEN
        RAISE EXCEPTION 'void reason must contain 1 to 1000 characters'
            USING ERRCODE = '22023';
    END IF;

    SELECT *
    INTO v_receipt
    FROM public.acknowledgement_receipts
    WHERE id = p_receipt_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE no_data_found;
    END IF;

    IF v_receipt.revision_number <> p_expected_revision THEN
        RAISE EXCEPTION 'acknowledgement receipt revision conflict'
            USING ERRCODE = '40001';
    END IF;

    IF v_receipt.voided_at IS NOT NULL THEN
        IF v_receipt.void_reason = v_reason THEN
            RETURN v_receipt;
        END IF;

        RAISE EXCEPTION 'receipt is already voided'
            USING ERRCODE = '55000';
    END IF;

    UPDATE public.acknowledgement_receipts
    SET
        voided_at = clock_timestamp(),
        void_reason = v_reason
    WHERE id = p_receipt_id
    RETURNING * INTO v_receipt;

    INSERT INTO public.acknowledgement_receipt_events (
        receipt_id,
        event_type,
        actor_role,
        revision_number,
        details
    )
    VALUES (
        p_receipt_id,
        'voided',
        'receiver',
        v_receipt.revision_number,
        jsonb_build_object('reason', v_reason)
    );

    RETURN v_receipt;
END;
$$;

