CREATE OR REPLACE FUNCTION public.ack_set_transaction_paid(
    p_transaction_id uuid,
    p_paid boolean,
    p_receipt_id uuid,
    p_expected_revision integer
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_transaction public.transactions%ROWTYPE;
    v_receipt public.acknowledgement_receipts%ROWTYPE;
    v_had_confirmation boolean;
BEGIN
    IF p_receipt_id IS NULL THEN
        SELECT *
        INTO v_transaction
        FROM public.transactions
        WHERE id = p_transaction_id
        FOR UPDATE;

        IF NOT FOUND THEN
            RAISE no_data_found;
        END IF;

        UPDATE public.transactions
        SET paid = p_paid
        WHERE id = p_transaction_id;

        RETURN jsonb_build_object(
            'transaction_id', p_transaction_id,
            'paid', p_paid,
            'receipt_id', NULL,
            'receipt_revision', NULL
        );
    END IF;

    IF NOT p_paid THEN
        RAISE EXCEPTION 'a receipt can only be linked while marking paid'
            USING ERRCODE = '22023';
    END IF;

    IF p_expected_revision IS NULL THEN
        RAISE EXCEPTION 'expected revision is required when linking a receipt'
            USING ERRCODE = '22023';
    END IF;

    SELECT *
    INTO v_receipt
    FROM public.acknowledgement_receipts
    WHERE id = p_receipt_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE no_data_found;
    END IF;

    IF v_receipt.revision_number <> p_expected_revision THEN
        RAISE EXCEPTION 'acknowledgement receipt revision conflict'
            USING ERRCODE = '40001';
    END IF;

    IF v_receipt.voided_at IS NOT NULL THEN
        RAISE EXCEPTION 'voided receipts cannot accept transaction references'
            USING ERRCODE = '55000';
